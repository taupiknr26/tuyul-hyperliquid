#!/usr/bin/env python3
"""Write hash-pinned lockfiles (SR-12, NFR-019).

    python scripts/make_lock.py            # from the project's virtualenv

Versions are taken from the packages installed in the current
environment (the set the test suite was run against). The dependency
closure is computed for CPython 3.11-3.13 on Linux and macOS, and the
sha256 of every published file of each pinned version is read from
PyPI's JSON API, so ``pip install --require-hashes`` works on any of
those platforms without this script downloading a single wheel.

Review the diff of the lockfiles before committing an update.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
import urllib.request
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
TARGETS = [
    {"python_version": v, "python_full_version": f"{v}.0", "sys_platform": p, "platform_system": s, "os_name": "posix",
     "implementation_name": "cpython", "platform_python_implementation": "CPython"}
    for v in ("3.11", "3.12", "3.13")
    for p, s in (("linux", "Linux"), ("darwin", "Darwin"))
]


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def closure(roots: list[str]) -> dict[str, str]:
    pinned: dict[str, str] = {}
    missing: set[str] = set()
    todo = [(Requirement(r), frozenset()) for r in roots]
    seen: set[tuple[str, frozenset]] = set()
    while todo:
        req, extras = todo.pop()
        name = canonical(req.name)
        key = (name, frozenset(req.extras) | extras)
        if key in seen:
            continue
        seen.add(key)
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            missing.add(name)
            continue
        pinned[name] = dist.version
        for raw in dist.requires or []:
            child = Requirement(raw)
            wanted = False
            for target in TARGETS:
                for extra in ("", *sorted(key[1])):
                    env = {**default_environment(), **target, "extra": extra}
                    if child.marker is None or child.marker.evaluate(env):
                        wanted = True
            if wanted:
                todo.append((child, frozenset(child.extras)))
    if missing:
        sys.exit(f"not installed here but required on a target platform: {', '.join(sorted(missing))}")
    return pinned


def hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        files = json.load(response)["urls"]
    digests = sorted({f["digests"]["sha256"] for f in files if not f.get("yanked")})
    if not digests:
        sys.exit(f"no files published for {name}=={version}")
    return digests


def write(path: Path, pinned: dict[str, str], header: str) -> None:
    lines = [f"# {line}" for line in header.splitlines()] + [""]
    for name in sorted(pinned):
        version = pinned[name]
        digests = hashes(name, version)
        lines.append(f"{name}=={version} \\")
        lines += [f"    --hash=sha256:{d}" + (" \\" if i < len(digests) - 1 else "") for i, d in enumerate(digests)]
    path.write_text("\n".join(lines) + "\n")
    print(f"{path.name}: {len(pinned)} packages")


def main() -> None:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    runtime = closure(project["dependencies"])
    dev = closure(project["dependencies"] + project["optional-dependencies"]["dev"])
    note = (
        "Generated by scripts/make_lock.py. Do not edit by hand.\n"
        "Install with: pip install --require-hashes -r {name}\n"
        "Targets: CPython 3.11-3.13 on Linux and macOS. Hashes are PyPI's published sha256 digests."
    )
    write(ROOT / "requirements.lock", runtime, note.format(name="requirements.lock"))
    write(ROOT / "requirements-dev.lock", dev, note.format(name="requirements-dev.lock"))


if __name__ == "__main__":
    main()
